import { z } from "zod";
import type { PageText } from "./jobs";

export const resultSchema = z.object({
  headline: z.string().min(3).max(200),
  summary: z.string().min(10).max(6000),
  answer: z.string().max(4000).nullable().optional(),
  points: z
    .array(
      z.object({
        text: z.string().min(3).max(600),
        pages: z.array(z.number().int()).min(1).max(8),
        quote: z.string().min(8).max(300),
      }),
    )
    .min(1)
    .max(20),
  uncertainties: z.array(z.string().max(400)).max(10).default([]),
  sensitive: z.boolean().default(false),
});

export type DocResult = {
  headline: string;
  summary: string;
  answer: string | null;
  points: { text: string; pages: number[]; quote: string; verified: boolean }[];
  uncertainties: string[];
  sensitive: boolean;
  filename: string;
  pageCount: number;
};

const norm = (s: string) => s.toLowerCase().replace(/[\s ]+/g, " ").replace(/[“”]/g, '"').replace(/[‘’]/g, "'").trim();

/** Validates structure, page references, and whether each quote appears on the cited pages. */
export function validateResult(raw: unknown, pages: PageText[], filename: string): DocResult {
  const r = resultSchema.parse(raw);
  const byN = new Map(pages.map((p) => [p.n, norm(p.text)]));
  const points = r.points.map((p) => {
    const refs = [...new Set(p.pages)];
    if (refs.some((n) => !byN.has(n))) throw new Error("page reference out of range");
    const q = norm(p.quote);
    return { text: p.text, pages: refs.sort((a, b) => a - b), quote: p.quote, verified: refs.some((n) => byN.get(n)!.includes(q)) };
  });
  return {
    headline: r.headline,
    summary: r.summary,
    answer: r.answer ?? null,
    points,
    uncertainties: r.uncertainties,
    sensitive: r.sensitive,
    filename,
    pageCount: pages.length,
  };
}

export function toMarkdown(r: DocResult, instruction: string): string {
  const L: string[] = [`# ${r.headline}`, "", `*Source: ${r.filename} (${r.pageCount} pages) — Request: ${instruction}*`, ""];
  if (r.answer) L.push("## Answer", "", r.answer, "");
  L.push("## Summary (AI interpretation)", "", r.summary, "", "## Key points", "");
  for (const p of r.points)
    L.push(`- ${p.text} *(p. ${p.pages.join(", ")}${p.verified ? "" : "; quote not matched — check source"})*`, `  > "${p.quote}"`);
  if (r.uncertainties.length) L.push("", "## Uncertainties", "", ...r.uncertainties.map((u) => `- ${u}`));
  L.push("", "---");
  if (r.sensitive)
    L.push("**Verify before relying on this.** This looks like financial or contractual material. AI summaries can miss or misread terms; check the cited pages and consult a qualified professional.");
  else L.push("Generated by AI. Quotes are copied from the document; the summary is AI interpretation. Check the cited pages for anything important.");
  return L.join("\n") + "\n";
}
